export function useDesktopI18n() {
  const { locale } = useI18n();
  return {
    locale,
    t: (key: keyof typeof en, values: Record<string, unknown> = {}) =>
      (locale === "zh-CN" ? zhCN : en)[key].replace(
        /\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""),
      ),
  };
}
