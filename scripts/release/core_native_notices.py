"""Generate Core's native dependency notices from the checksum-locked Cargo cache.

Requires Python 3.11+. Populate the cache with `cargo fetch --locked --manifest-path
packages/core/rust/Cargo.toml` (no target filter). This script never uses the network.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import os
import re
import sys
import tarfile
from pathlib import Path

import tomllib

ROOT = Path(__file__).resolve().parents[2]
LOCK = ROOT / "packages/core/rust/Cargo.lock"
OUTPUT = ROOT / "packages/core/THIRD_PARTY_NOTICES.md"
MATERIALS = Path(__file__).with_suffix(".toml")
REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"
LOCAL_CRATE = ("wenyi-core-native", "0.0.0")
SHA256 = re.compile(r"[0-9a-f]{64}")
MEMBER = re.compile(r"([\w./-]+)(?:#L([1-9][0-9]*)-L([1-9][0-9]*))?")

HEADER = """# Third-party notices for the wenyi-core native extension

Generated by `scripts/release/core_native_notices.py` from
`packages/core/rust/Cargo.lock` and reviewed upstream materials. Do not edit by hand.

This inventory includes **every crates.io package in the native extension's lockfile**
across targets. It intentionally overincludes target-specific, optional, build,
test, and development dependencies. Inclusion does not mean a crate is present
in every binary. The native extension's own code is not a third-party dependency.
Dependencies retain their upstream licenses; the license column reproduces their
Cargo declarations, not a new license grant. Additional terms and notices for
incorporated code or data appear in the linked materials.

Rust toolchain components and libraries supplied independently of this Cargo
lockfile are outside the scope of this inventory. In a Core wheel, the building
toolchain's own standard-library notices are in `wenyi_core/_licenses/rust-std/`.

## Locked packages

| Package | Version | Declared license | Upstream materials |
| --- | --- | --- | --- |
"""


class NoticeError(Exception):
    """A locked dependency or notice could not be verified."""


def locked_crates(lock: Path) -> dict[str, str]:
    with lock.open("rb") as stream:
        data = tomllib.load(stream)
    if data.get("version") not in (3, 4) or not isinstance(data.get("package"), list):
        raise NoticeError(f"{lock}: unrecognized Cargo.lock format")

    crates: dict[str, str] = {}
    found_local = False
    for entry in data["package"]:
        if not isinstance(entry, dict):
            raise NoticeError(f"{lock}: malformed package entry")
        name, version = entry.get("name", ""), entry.get("version", "")
        if not isinstance(name, str) or not isinstance(version, str):
            raise NoticeError(f"{lock}: malformed package identity")
        identity = f"{name} {version}"
        if entry.get("source") is None and (name, version) == LOCAL_CRATE and not found_local:
            if "checksum" not in entry:
                found_local = True
                continue
        if entry.get("source") != REGISTRY:
            raise NoticeError(f"{identity}: unsupported or duplicate local package/source")
        if not re.fullmatch(r"[A-Za-z0-9_-]+", name) or not re.fullmatch(
            r"[0-9]+\.[0-9]+\.[0-9]+(?:[-+][A-Za-z0-9.+-]+)?", version
        ):
            raise NoticeError(f"{identity}: invalid locked package identity")
        checksum = entry.get("checksum")
        if not isinstance(checksum, str) or not SHA256.fullmatch(checksum):
            raise NoticeError(f"{identity}: missing or invalid Cargo.lock SHA-256")
        if identity in crates:
            raise NoticeError(f"{identity}: duplicate locked package")
        crates[identity] = checksum
    if not found_local or not crates:
        raise NoticeError(f"{lock}: expected {LOCAL_CRATE[0]} and its registry dependencies")
    return crates


def review_digest(crates: dict[str, str]) -> str:
    snapshot = "".join(f"{identity} {sha}\n" for identity, sha in sorted(crates.items()))
    return hashlib.sha256(snapshot.encode("utf-8")).hexdigest()


def check_materials(data: dict, crates: dict[str, str]) -> dict[str, list[str]]:
    if set(data) != {"review_sha256", "group", "extra", "supplement", "note"}:
        raise NoticeError("unrecognized notice material tables")
    reviewed: dict[str, list[str]] = {}
    used_supplements = set()
    for group in data["group"].values():
        if set(group) != {"files", "crates"}:
            raise NoticeError("unrecognized notice group fields")
        for identity in group["crates"]:
            if identity in reviewed or identity not in crates:
                raise NoticeError(f"{identity}: duplicate or unlocked notice review")
            refs = group["files"] + data["extra"].get(identity, [])
            if not refs or len(set(refs)) != len(refs):
                raise NoticeError(f"{identity}: missing or duplicate notice materials")
            for ref in refs:
                if ref.startswith("@"):
                    key = ref[1:]
                    if key not in data["supplement"]:
                        raise NoticeError(f"{identity}: missing supplemental material {ref}")
                    used_supplements.add(key)
            reviewed[identity] = refs
    if missing := crates.keys() - reviewed.keys():
        raise NoticeError(f"unreviewed locked packages: {', '.join(sorted(missing))}")
    if data["review_sha256"] != (digest := review_digest(crates)):
        raise NoticeError(
            f"locked archive checksums changed; review materials before setting review_sha256 = {digest!r}"
        )
    if unused := (data["extra"].keys() | data["note"].keys()) - crates.keys():
        raise NoticeError(f"materials for unlocked packages: {', '.join(sorted(unused))}")
    if unused := data["supplement"].keys() - used_supplements:
        raise NoticeError(f"unused supplemental materials: {', '.join(sorted(unused))}")
    return reviewed


def read_archive(cache: Path, stem: str, checksum: str) -> bytes:
    candidates = sorted(cache.glob(f"*/{stem}.crate"))
    if not candidates:
        raise NoticeError(f"{stem}: missing .crate archive in {cache}; run cargo fetch --locked")
    for candidate in candidates:
        payload = candidate.read_bytes()
        if hashlib.sha256(payload).hexdigest() == checksum:
            return payload
    raise NoticeError(f"{stem}: no cached archive matches the Cargo.lock checksum")


def archive_material(
    archive: tarfile.TarFile, members: dict[str, tarfile.TarInfo], stem: str, ref: str
) -> str:
    match = MEMBER.fullmatch(ref)
    if not match or ".." in match[1].split("/") or match[1].startswith("/"):
        raise NoticeError(f"{stem}: invalid material selector {ref}")
    member = members.get(f"{stem}/{match[1]}")
    if member is None or not member.isfile():
        raise NoticeError(f"{stem}: missing regular archive member {ref}")
    with archive.extractfile(member) as stream:
        text = stream.read().decode("utf-8-sig")
    if match[2]:
        lines = text.splitlines()
        start, end = int(match[2]), int(match[3])
        if not 1 <= start <= end <= len(lines):
            raise NoticeError(f"{stem}: material excerpt out of range: {ref}")
        text = "\n".join(lines[start - 1 : end])
    return text


def read_package(
    cache: Path, identity: str, checksum: str, refs: list[str]
) -> tuple[str, dict[str, str]]:
    name, version = identity.split()
    stem = f"{name}-{version}"
    with tarfile.open(fileobj=io.BytesIO(read_archive(cache, stem, checksum)), mode="r:gz") as tar:
        entries = tar.getmembers()
        members = {member.name: member for member in entries}
        if len(entries) != len(members):
            raise NoticeError(f"{identity}: archive contains duplicate paths")
        manifest = tomllib.loads(archive_material(tar, members, stem, "Cargo.toml"))["package"]
        if manifest.get("name") != name or manifest.get("version") != version:
            raise NoticeError(f"{identity}: cached Cargo.toml has a different identity")
        license_ = manifest.get("license")
        if not isinstance(license_, str) or not license_.strip() or "\n" in license_:
            raise NoticeError(f"{identity}: missing or malformed upstream license declaration")
        texts = {
            ref: archive_material(tar, members, stem, ref)
            for ref in refs
            if not ref.startswith("@")
        }
    return license_, texts


def render(lock: Path, materials: Path, cache: Path) -> bytes:
    crates = locked_crates(lock)
    with materials.open("rb") as stream:
        data = tomllib.load(stream)
    reviewed = check_materials(data, crates)
    rows = [HEADER.rstrip("\n")]
    bodies: dict[str, tuple[str, str]] = {}
    supplement_sources: dict[str, str] = {}
    for identity, checksum in sorted(crates.items()):
        refs = reviewed[identity]
        license_, texts = read_package(cache, identity, checksum, refs)
        links = []
        for ref in refs:
            if ref.startswith("@"):
                supplemental = data["supplement"][ref[1:]]
                if set(supplemental) != {"source", "text"} or not supplemental["source"].startswith(
                    "https://"
                ):
                    raise NoticeError(f"{identity}: invalid supplemental material {ref}")
                label = ref[1:]
                raw = supplemental["text"]
                supplement_sources[label] = supplemental["source"]
            else:
                label = ref
                raw = texts[ref]
            text = "\n".join(line.rstrip() for line in raw.splitlines()).strip("\n")
            if not text.strip() or "\0" in text:
                raise NoticeError(f"{identity}: empty or invalid notice material {ref}")
            # Only whitespace differences are ignored. Copyright wording, license
            # variants, and exceptions stay distinct, even for the same SPDX ID.
            key = " ".join(text.split())
            if key not in bodies:
                bodies[key] = (f"material-{len(bodies) + 1:03}", text)
            anchor, _ = bodies[key]
            links.append(f"[`{label}`](#{anchor})")
        name, version = identity.split()
        rows.append(f"| `{name}` | `{version}` | `{license_}` | {', '.join(links)} |")

    if data["note"]:
        rows.extend(("", "## Attribution notes", ""))
        rows.extend(f"- **{identity}:** {note}" for identity, note in sorted(data["note"].items()))
    if supplement_sources:
        rows.extend(("", "## Supplemental upstream sources", ""))
        rows.extend(f"- [{key}]({source})" for key, source in sorted(supplement_sources.items()))
    rows.extend(("", "## License and notice texts"))
    for anchor, text in bodies.values():
        # Upstream Markdown or source comments must render literally.
        fence = "`" * max(3, 1 + max((len(s) for s in re.findall(r"`+", text)), default=0))
        rows.extend(("", f"### {anchor}", "", fence, text, fence))
    return ("\n".join(rows) + "\n").encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="verify the committed bytes; do not write"
    )
    args = parser.parse_args()
    cargo_home = Path(os.environ.get("CARGO_HOME") or Path.home() / ".cargo")
    try:
        expected = render(LOCK, MATERIALS, cargo_home / "registry/cache")
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_bytes() != expected:
                raise NoticeError(
                    f"{OUTPUT.relative_to(ROOT)} is missing or stale; rerun without --check"
                )
        else:
            OUTPUT.write_bytes(expected)
    except (NoticeError, OSError, tarfile.TarError, ValueError, KeyError, TypeError) as exc:
        print(f"core native notices: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
